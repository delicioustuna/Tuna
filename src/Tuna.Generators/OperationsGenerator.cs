using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Tuna.Generators;

/// <summary>
/// Source generator that emits elementwise, pairwise, type-inference, and fixed-element-type overloads and operator structs for attributed methods.
/// <para>属性が付与されたメソッドに対して、要素ごと演算・列ペア演算・型推論・要素型固定のオーバーロードおよび演算子構造体を生成するソースジェネレーターです。</para>
/// </summary>
/// <remarks>
/// <para>Processes <c>ElementwiseOperationAttribute</c>, <c>PairwiseOperationAttribute</c>, <c>InferenceOverloadsAttribute</c>, and <c>FixedElementTypeOverloadsAttribute</c>.</para>
/// <para><c>ElementwiseOperationAttribute</c>、<c>PairwiseOperationAttribute</c>、<c>InferenceOverloadsAttribute</c>、<c>FixedElementTypeOverloadsAttribute</c> を処理します。</para>
/// </remarks>
[Generator]
public sealed partial class OperationsGenerator : IIncrementalGenerator
{
    private const string Root = "Tuna";
    private const string ViewNamespace = "Tuna.LinearAlgebra";

    private static readonly DiagnosticDescriptor InvalidTarget = new(
        "TNG001", "生成対象のメソッドの形が合わない", "{0}",
        "Tuna.Generators", DiagnosticSeverity.Error, isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor DuplicateOperator = new(
        "TNG002", "生成する演算子の名前が重複している", "{0}",
        "Tuna.Generators", DiagnosticSeverity.Error, isEnabledByDefault: true);

    private static readonly SymbolDisplayFormat CrefFormat = new(
        globalNamespaceStyle: SymbolDisplayGlobalNamespaceStyle.Omitted,
        typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
        genericsOptions: SymbolDisplayGenericsOptions.IncludeTypeParameters,
        miscellaneousOptions: SymbolDisplayMiscellaneousOptions.UseSpecialTypes);

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterSourceOutput(Collect(context, "InferenceOverloads",
            static (m, _, _) => Generated.For("InferenceOverloads", m, InferenceVariants(Shape.From(m)))), Emit);
        context.RegisterSourceOutput(Collect(context, "FixedElementTypeOverloads",
            static (m, a, _) => Generated.For("FixedElementTypeOverloads", m, FixedElementTypeOverloads(m, a))), Emit);
        // 演算子名の重複は両属性にまたがって検査するため、結合して出力する。
        var elementwise = Collect(context, "ElementwiseOperation", static (m, a, c) => UserOperation(m, a, pairwise: false, c));
        var pairwise = Collect(context, "PairwiseOperation", static (m, a, c) => UserOperation(m, a, pairwise: true, c));
        context.RegisterSourceOutput(elementwise.Combine(pairwise), static (spc, items) => Emit(spc, items.Left.AddRange(items.Right)));
    }

    private static IncrementalValueProvider<ImmutableArray<Generated>> Collect(IncrementalGeneratorInitializationContext context, string attribute,
        Func<IMethodSymbol, AttributeData, Compilation, Generated> generate) =>
        context.SyntaxProvider.ForAttributeWithMetadataName(
            $"{Root}.{attribute}Attribute",
            static (node, _) => node is MethodDeclarationSyntax,
            (ctx, _) => ctx.Attributes.Select(a => generate((IMethodSymbol)ctx.TargetSymbol, a, ctx.SemanticModel.Compilation)).ToImmutableArray())
            .SelectMany(static (items, _) => items).Collect();

    private static void Emit(SourceProductionContext spc, ImmutableArray<Generated> items)
    {
        foreach (var error in items.Where(g => g.Error is not null))
        {
            spc.ReportDiagnostic(Diagnostic.Create(InvalidTarget, error.Location, error.Error));
        }

        var duplicates = new HashSet<Generated>();
        foreach (var group in items.Where(g => g.Error is null && g.OperatorKey is not null).GroupBy(g => g.OperatorKey).Where(g => g.Count() > 1))
        {
            string sources = string.Join("、", group.Select(g => g.Source));
            foreach (var g in group)
            {
                duplicates.Add(g);
                spc.ReportDiagnostic(Diagnostic.Create(DuplicateOperator, g.Location,
                    $"演算子 {g.OperatorKey} を生成するメソッドが複数あります（{sources}）。属性の OperatorName で別の名前を付けてください"));
            }
        }

        var valid = items.Where(g => g.Error is null && (g.Code.Length > 0 || g.OperatorCode.Length > 0) && !duplicates.Contains(g));
        foreach (var group in valid.GroupBy(g => (g.Kind, g.Container)).OrderBy(g => g.Key.Kind, StringComparer.Ordinal).ThenBy(g => g.Key.Container, StringComparer.Ordinal))
        {
            var (header, footer, name) = Wrap(group.Key.Container);
            var sb = new StringBuilder("// <auto-generated/>\n#nullable enable\n").Append(header);
            var nested = new SortedDictionary<string, StringBuilder>(StringComparer.Ordinal);
            foreach (var g in group.OrderBy(g => g.Code, StringComparer.Ordinal).ThenBy(g => g.OperatorCode, StringComparer.Ordinal))
            {
                if (g.OperatorContainer is null)
                {
                    sb.Append(g.OperatorCode);
                }
                else
                {
                    if (!nested.TryGetValue(g.OperatorContainer, out var codes))
                    {
                        nested.Add(g.OperatorContainer, codes = new StringBuilder());
                    }

                    codes.Append(g.OperatorCode);
                }

                sb.Append(g.Code);
            }

            foreach (var container in nested)
            {
                sb.Append("    /// <summary>Generated operators for use with <c>XMath.Map</c>, <c>Zip</c>, and <c>Pairwise</c>. <para><c>XMath.Map</c>、<c>Zip</c>、<c>Pairwise</c> に渡すために生成された演算子です。</para></summary>\n")
                    .Append($"    public static partial class {container.Key}\n    {{\n").Append(Indent(container.Value.ToString())).Append("    }\n\n");
            }

            sb.Append(footer);
            spc.AddSource($"{name}.{group.Key.Kind}.g.cs", sb.ToString());
        }
    }

    // 増分生成のキャッシュ比較が値等価で機能するよう、生成ソースを文字列で保持する。
    private sealed record Generated(string Kind, string Container, string Code, string? Error = null, Location? Location = null,
        string OperatorCode = "", string? OperatorContainer = null, string? OperatorKey = null, string? Source = null)
    {
        public static Generated For(string kind, IMethodSymbol method, string code) => new(kind, ContainerKey(method.ContainingType), code);

        public static Generated Invalid(string kind, IMethodSymbol method, string error) => new(kind, "", "", error, method.Locations.FirstOrDefault());
    }

    // ---------- 型の分類 ----------

    private enum ViewKind { ReadOnly, Writable, Container }

    private sealed record View(int Rank, ViewKind Kind, string Element)
    {
        public View(bool isMatrix, ViewKind kind, string element) : this(isMatrix ? 2 : 1, kind, element)
        {
        }
    }

    private static View? AsView(ITypeSymbol type)
    {
        if (type is not INamedTypeSymbol { TypeArguments.Length: 1 } named || named.ContainingNamespace.ToDisplayString() != ViewNamespace)
        {
            return null;
        }

        string element = Display(named.TypeArguments[0]);
        return named.Name switch
        {
            "ReadOnlyVectorSpan" => new View(1, ViewKind.ReadOnly, element),
            "VectorSpan" => new View(1, ViewKind.Writable, element),
            "ReadOnlyMatrixSpan" => new View(2, ViewKind.ReadOnly, element),
            "MatrixSpan" => new View(2, ViewKind.Writable, element),
            "ReadOnlyTensorSpan" => new View(3, ViewKind.ReadOnly, element),
            "TensorSpan" => new View(3, ViewKind.Writable, element),
            _ => null,
        };
    }

    private static string TypeOf(bool isMatrix, ViewKind kind, string element) => TypeOf(isMatrix ? 2 : 1, kind, element);

    private static string TypeOf(int rank, ViewKind kind, string element)
    {
        string name = (rank, kind) switch
        {
            (1, ViewKind.ReadOnly) => "ReadOnlyVectorSpan",
            (1, ViewKind.Writable) => "VectorSpan",
            (1, ViewKind.Container) => "Vector",
            (2, ViewKind.ReadOnly) => "ReadOnlyMatrixSpan",
            (2, ViewKind.Writable) => "MatrixSpan",
            (2, ViewKind.Container) => "Matrix",
            (_, ViewKind.ReadOnly) => "ReadOnlyTensorSpan",
            (_, ViewKind.Writable) => "TensorSpan",
            _ => "Tensor",
        };
        return $"global::{ViewNamespace}.{name}<{element}>";
    }

    private static string Display(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    // ---------- メソッドの形 ----------

    private sealed record Parameter(string Type, string Name, View? View);

    private sealed record Shape(string Name, string[] TypeParameters, string Constraints, string ReturnType, bool ReturnsVoid,
        Parameter[] Parameters, string Cref, string Accessibility)
    {
        public static Shape From(IMethodSymbol m) => new(
            m.Name, m.TypeParameters.Select(t => t.Name).ToArray(), OperationsGenerator.Constraints(m.TypeParameters, s => s), Display(m.ReturnType), m.ReturnsVoid,
            m.Parameters.Select(p => new Parameter(Display(p.Type), p.Name, AsView(p.Type))).ToArray(), OperationsGenerator.Cref(m), AccessibilityText(m.DeclaredAccessibility));

        public string TypeArguments => TypeParameters.Length == 0 ? "" : $"<{string.Join(", ", TypeParameters)}>";
    }

    private static string InferenceVariants(Shape shape)
    {
        var parameters = shape.Parameters;
        int last = parameters.Length - 1;
        bool hasDestination = last >= 0 && parameters[last].Name == "destination" && parameters[last].View?.Kind == ViewKind.Writable;
        var sb = new StringBuilder();

        void Emit(Func<int, View, ViewKind> replace, string? returnType, bool returnDestination)
        {
            var declared = parameters.Select((p, i) => $"{(p.View is { } v ? TypeOf(v.Rank, replace(i, v), v.Element) : p.Type)} {p.Name}");
            var arguments = parameters.Select(p => p.View is not null ? $"({p.Type}){p.Name}" : p.Name);
            string call = $"{shape.Name}{shape.TypeArguments}({string.Join(", ", arguments)})";
            string body = returnDestination ? $"{call};\n        return destination;" : shape.ReturnsVoid ? $"{call};" : $"return {call};";
            sb.Append(Method($"<inheritdoc cref=\"{shape.Cref}\"/>", shape.Accessibility, returnType ?? shape.ReturnType,
                shape.Name + shape.TypeArguments, string.Join(", ", declared), shape.Constraints, body));
        }

        if (hasDestination)
        {
            var d = parameters[last].View!;
            string returnType = TypeOf(d.Rank, ViewKind.Container, d.Element);
            Emit((_, _) => ViewKind.Container, returnType, returnDestination: true);
            // Infer the element type from the destination even when the inputs mix views and containers.
            // With no other view arguments this would duplicate the all-container overload above.
            if (parameters.Take(last).Any(p => p.View is not null))
            {
                Emit((i, v) => i == last ? ViewKind.Container : v.Kind, returnType, returnDestination: true);
            }
        }
        else if (parameters.Any(p => p.View?.Kind == ViewKind.ReadOnly))
        {
            Emit((_, v) => v.Kind == ViewKind.ReadOnly ? ViewKind.Writable : v.Kind, null, false);
            Emit((_, v) => v.Kind == ViewKind.ReadOnly ? ViewKind.Container : v.Kind, null, false);
        }
        else if (parameters.Any(p => p.View?.Kind == ViewKind.Writable))
        {
            Emit((_, v) => v.Kind == ViewKind.Writable ? ViewKind.Container : v.Kind, null, false);
        }

        return sb.ToString();
    }

    private static string FixedElementTypeOverloads(IMethodSymbol method, AttributeData attribute)
    {
        var element = method.TypeParameters[0];
        var remaining = method.TypeParameters.Skip(1).ToArray();
        var pattern = new Regex(@"(?<![\w.])" + Regex.Escape(element.Name) + @"(?!\w)");
        var types = attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Kind == TypedConstantKind.Array
            ? attribute.ConstructorArguments[0].Values.Select(v => v.Value).OfType<ITypeSymbol>()
            : Enumerable.Empty<ITypeSymbol>();
        var sb = new StringBuilder();
        foreach (var type in types)
        {
            string fixedType = Display(type);
            string Substitute(string text) => pattern.Replace(text, fixedType);
            string typeParameters = remaining.Length == 0 ? "" : $"<{string.Join(", ", remaining.Select(t => t.Name))}>";
            var declared = method.Parameters.Select(p => $"{Substitute(Display(p.Type))} {p.Name}");
            string call = $"{method.Name}<{string.Join(", ", new[] { fixedType }.Concat(remaining.Select(t => t.Name)))}>"
                + $"({string.Join(", ", method.Parameters.Select(p => p.Name))})";
            sb.Append(Method($"<inheritdoc cref=\"{Cref(method)}\"/>", AccessibilityText(method.DeclaredAccessibility), Substitute(Display(method.ReturnType)),
                method.Name + typeParameters, string.Join(", ", declared), Constraints(remaining, Substitute),
                method.ReturnsVoid ? $"{call};" : $"return {call};"));
        }

        return sb.ToString();
    }

    // ---------- [ElementwiseOperation] / [PairwiseOperation] ----------

    private sealed record UserSpec(IParameterSymbol[] Inputs, string OperatorName, string? OperatorContainer);

    private static string? Validate(IMethodSymbol method, AttributeData attributeData, bool pairwise, out UserSpec spec)
    {
        string attribute = pairwise ? "PairwiseOperation" : "ElementwiseOperation";
        string? operatorName = NamedString(attributeData, "OperatorName");
        string? container = NamedString(attributeData, "OperatorContainer");
        string[]? over = pairwise ? null : NamedStrings(attributeData, "Over");
        var p = method.Parameters;
        spec = new UserSpec(Array.Empty<IParameterSymbol>(), operatorName ?? method.Name + "Operator", container);
        for (var type = method.ContainingType; type is not null; type = type.ContainingType)
        {
            if (type.IsExtension)
            {
                // 演算子の構造体を入れ子にできないため
                return $"[{attribute}] を付けたメソッド {method.Name} は拡張ブロックの中に置けません。partial class に直接置いてください";
            }

            bool isPartial = type.DeclaringSyntaxReferences.Any(r =>
                r.GetSyntax() is TypeDeclarationSyntax t && t.Modifiers.Any(SyntaxKind.PartialKeyword));
            if (!isPartial || type.TypeParameters.Length > 0 || type.TypeKind != TypeKind.Class)
            {
                return $"[{attribute}] を付けたメソッド {method.Name} を含む型 {type.Name} は、型引数のない partial class にしてください";
            }
        }

        if (!method.IsStatic || method.TypeParameters.Length > 1 || p.Length < (pairwise ? 2 : 1) || p.Any(x => x.RefKind != RefKind.None))
        {
            return $"[{attribute}] を付けたメソッド {method.Name} は、型引数が高々1つの static メソッドで、ref/out/in の引数を持たないこと";
        }

        if (p.Any(x => x.Name == "destination"))
        {
            return $"[{attribute}] を付けたメソッド {method.Name} の引数名 destination は出力先版で使うので、別の名前にしてください";
        }

        if (!IsIdentifier(spec.OperatorName))
        {
            return $"[{attribute}] の OperatorName に指定した \"{spec.OperatorName}\" は型の名前に使えません";
        }

        if (container is null && spec.OperatorName == method.Name)
        {
            return $"[{attribute}] の OperatorName を {method.Name} にする場合は、メソッドと名前が衝突しないよう OperatorContainer も指定してください";
        }

        if (container is not null && (!IsIdentifier(container) || container == "InPlace"))
        {
            return $"[{attribute}] の OperatorContainer に指定した \"{container}\" はクラスの名前に使えません（InPlace はその場更新の版の置き場所）";
        }

        string e = Display(method.ReturnType);
        if (pairwise)
        {
            if (AsView(p[0].Type) is not { Rank: 1, Kind: ViewKind.ReadOnly } v0
                || AsView(p[1].Type) is not { Rank: 1, Kind: ViewKind.ReadOnly } v1 || v0.Element != e || v1.Element != e)
            {
                return $"[PairwiseOperation] を付けたメソッド {method.Name} は static E {method.Name}(ReadOnlyVectorSpan<E> x, ReadOnlyVectorSpan<E> y, ...) の形にしてください";
            }

            spec = spec with { Inputs = new[] { p[0], p[1] } };
            return null;
        }

        if (over is null)
        {
            if (Display(p[0].Type) != e)
            {
                return $"[ElementwiseOperation] を付けたメソッド {method.Name} は、最初の引数と戻り値が同じ要素型であること（static E {method.Name}(E x, ...)）";
            }

            spec = spec with { Inputs = new[] { p[0] } };
            return null;
        }

        if (over.Length is < 1 or > 3 || over.Distinct().Count() != over.Length)
        {
            return $"[ElementwiseOperation] の Over には、{method.Name} の異なる引数の名前を1〜3個指定してください";
        }

        foreach (string name in over)
        {
            var parameter = p.FirstOrDefault(x => x.Name == name);
            if (parameter is null)
            {
                return $"[ElementwiseOperation] の Over に指定した \"{name}\" は {method.Name} の引数にありません";
            }

            if (Display(parameter.Type) != e)
            {
                return $"[ElementwiseOperation] の Over に指定した引数 {name} は、{method.Name} の戻り値と同じ要素型 {e} であること";
            }
        }

        spec = spec with { Inputs = p.Where(x => over.Contains(x.Name)).ToArray() };
        return null;
    }

    private static Generated UserOperation(IMethodSymbol method, AttributeData attributeData, bool pairwise, Compilation compilation)
    {
        string kind = pairwise ? "PairwiseOperation" : "ElementwiseOperation";
        if (Validate(method, attributeData, pairwise, out var spec) is { } error)
        {
            return Generated.Invalid(kind, method, error);
        }

        string e = Display(method.ReturnType);
        string typeParameters = method.TypeParameters.Length == 0 ? "" : $"<{method.TypeParameters[0].Name}>";
        string constraints = Constraints(method.TypeParameters, s => s);
        string access = AccessibilityText(method.DeclaredAccessibility);
        var parameters = method.Parameters;
        var isInput = parameters.Select(p => spec.Inputs.Contains(p, SymbolEqualityComparer.Default)).ToArray();
        var extras = parameters.Where((_, i) => !isInput[i]).Select(p => (Type: Display(p.Type), p.Name)).ToArray();
        int inputs = spec.Inputs.Length;
        bool stateful = extras.Length > 0;
        string op = spec.OperatorName + typeParameters;
        string opReference = (spec.OperatorContainer is null ? "" : spec.OperatorContainer + ".") + op;
        string newOp = $"new {opReference}({string.Join(", ", extras.Select(x => x.Name))})";
        string scalar = $"<see cref=\"{method.ContainingType.ToDisplayString(CrefFormat)}.{Cref(method)}\"/>";
        string inputNames = string.Join(", ", spec.Inputs.Select(p => p.Name));
        string kernel = pairwise ? "Pairwise" : inputs == 1 ? "Map" : "Zip";

        // 同一アセンブリ内でアクセサーを追加できるよう partial にし、名前衝突を避けるため元のメソッドは完全修飾名で呼び出す。
        string interfaceName = (pairwise ? "Pairwise" : inputs switch { 1 => "Unary", 2 => "Binary", _ => "Ternary" }) + "Operator";
        interfaceName = (stateful ? "IStateful" : "I") + interfaceName;
        string inputType = pairwise ? TypeOf(false, ViewKind.ReadOnly, e) : e;
        string invokeParameters = string.Join(", ", spec.Inputs.Select(p => $"{inputType} {p.Name}"));
        string invokeCall = $"{Display(method.ContainingType)}.{method.Name}{typeParameters}"
            + $"({string.Join(", ", parameters.Select((p, i) => isInput[i] ? p.Name : "this." + p.Name))})";
        // 入れ子クラス内では外側の型から参照できるよう、非公開メソッドの演算子を internal にする。
        string operatorAccess = spec.OperatorContainer is not null && access != "public" ? "internal" : access;
        var operatorCode = new StringBuilder();
        operatorCode.Append($"    /// <summary>Operator wrapper for {scalar} for use with <c>XMath.{kernel}</c>. <para>{scalar} を <c>XMath.{kernel}</c> に渡すための演算子です。</para></summary>\n");
        operatorCode.Append($"    {operatorAccess} readonly partial struct {op} : global::{Root}.{interfaceName}<{e}>\n{Indent(constraints)}    {{\n");
        foreach (var x in extras)
        {
            operatorCode.Append($"        private readonly {x.Type} {x.Name};\n");
        }

        if (stateful)
        {
            operatorCode.Append($"\n        /// <summary>Initializes a new instance storing the additional arguments for {scalar}. <para>{scalar} の追加引数を保持して初期化します。</para></summary>\n");
            operatorCode.Append($"        public {spec.OperatorName}({string.Join(", ", extras.Select(x => $"{x.Type} {x.Name}"))})\n        {{\n");
            foreach (var x in extras)
            {
                operatorCode.Append($"            this.{x.Name} = {x.Name};\n");
            }

            operatorCode.Append("        }\n\n");
        }

        operatorCode.Append($"        /// <summary>Invokes {scalar}. <para>{scalar} を呼び出します。</para></summary>\n");
        operatorCode.Append($"        public {(stateful ? "" : "static ")}{e} Invoke({invokeParameters}) => {invokeCall};\n    }}\n\n");

        string operations = $"global::{Root}.XMath";
        var sb = new StringBuilder();
        var shapes = new List<Shape>();
        foreach (bool isMatrix in pairwise ? new[] { true } : new[] { false, true })
        {
            string input = TypeOf(isMatrix, ViewKind.ReadOnly, e);
            string result = TypeOf(isMatrix, ViewKind.Container, e);
            string destination = TypeOf(isMatrix, ViewKind.Writable, e);
            var declared = parameters.Select((p, i) => isInput[i]
                ? new Parameter(input, p.Name, new View(isMatrix, ViewKind.ReadOnly, e))
                : new Parameter(Display(p.Type), p.Name, null)).ToArray();
            string callee = $"{operations}.{kernel}<{e}, {opReference}>";
            string operand = stateful ? $", {newOp}" : "";
            string actionEn = isMatrix
                ? (pairwise ? "to every pair of columns of the input matrices (<c>result[i, j]</c> corresponds to column i and column j)" : "elementwise to the input matrix")
                : "elementwise to the input vector";
            string actionJa = isMatrix
                ? (pairwise ? "入力行列の列の組ごとに適用し（<c>result[i, j]</c> は列 i と列 j の値）、" : "行列の要素ごとに適用し、")
                : "ベクトルの要素ごとに適用し、";
            string allocatedEn = isMatrix ? "a new matrix" : "a new vector";
            string allocatedJa = isMatrix ? "新しい行列を返します" : "新しいベクトルを返します";

            var allocating = new Shape(method.Name, method.TypeParameters.Select(t => t.Name).ToArray(), constraints, result, false,
                declared, "", access);
            sb.Append(Method($"<summary>Applies {scalar} {actionEn} and returns {allocatedEn}. <para>{scalar} を{actionJa}{allocatedJa}。</para></summary>", access, result, method.Name + typeParameters,
                Declare(allocating.Parameters), constraints, $"return {callee}({inputNames}{operand});"));
            var withDestination = allocating with
            {
                ReturnType = destination,
                Parameters = allocating.Parameters.Concat(new[] { new Parameter(destination, "destination", new View(isMatrix, ViewKind.Writable, e)) }).ToArray(),
            };
            sb.Append(Method($"<summary>Applies {scalar} {actionEn}, writes the result to <paramref name=\"destination\"/>, and returns it. <para>{scalar} を{actionJa}結果を <paramref name=\"destination\"/> に書き込んで返します。</para></summary>", access, destination,
                method.Name + typeParameters, Declare(withDestination.Parameters), constraints, $"return {callee}({inputNames}{operand}, destination);"));
            shapes.Add(allocating);
            shapes.Add(withDestination);
        }

        if (typeParameters.Length > 0)
        {
            foreach (var shape in shapes)
            {
                sb.Append(InferenceVariants(shape with { Cref = CrefOf(shape) }));
            }
        }

        // 単一入力の要素ごと演算にのみ InPlace クラスを生成する。
        if (!pairwise && inputs == 1)
        {
            var inPlace = new StringBuilder();
            var inPlaceShapes = new List<Shape>();
            string target = spec.Inputs[0].Name;
            foreach (bool isMatrix in new[] { false, true })
            {
                var declared = parameters.Select((p, i) => isInput[i]
                    ? new Parameter(TypeOf(isMatrix, ViewKind.Writable, e), p.Name, new View(isMatrix, ViewKind.Writable, e))
                    : new Parameter(Display(p.Type), p.Name, null)).ToArray();
                var shape = new Shape(method.Name, method.TypeParameters.Select(t => t.Name).ToArray(), constraints, "void", true, declared, "", access);
                string call = $"{operations}.InPlace.Map<{e}, {opReference}>({target}{(stateful ? $", {newOp}" : "")});";
                inPlace.Append(Method($"<summary>Applies {scalar} elementwise in place, overwriting <paramref name=\"{target}\"/>. <para>{scalar} を要素ごとにインプレースで適用し、<paramref name=\"{target}\"/> を上書きします。</para></summary>", access, "void",
                    method.Name + typeParameters, Declare(shape.Parameters), constraints, call));
                inPlaceShapes.Add(shape);
            }

            if (typeParameters.Length > 0)
            {
                foreach (var shape in inPlaceShapes)
                {
                    inPlace.Append(InferenceVariants(shape with { Cref = "InPlace." + CrefOf(shape) }));
                }
            }

            sb.Append("    /// <summary>Provides in-place elementwise operations that overwrite their input. <para>入力をインプレースで上書きする要素ごとの演算を提供します。</para></summary>\n    public static partial class InPlace\n    {\n")
                .Append(Indent(inPlace.ToString())).Append("    }\n\n");
        }

        if (!pairwise && GenerateDifferentiation(sb, method, attributeData, spec, compilation, scalar, access) is { } derivativeError)
        {
            return Generated.Invalid(kind, method, derivativeError);
        }

        string operatorKey = $"{method.ContainingType.ToDisplayString()}.{opReference}";
        return new Generated(kind, ContainerKey(method.ContainingType), sb.ToString(), Location: method.Locations.FirstOrDefault(),
            OperatorCode: operatorCode.ToString(), OperatorContainer: spec.OperatorContainer, OperatorKey: operatorKey,
            Source: method.ToDisplayString(SymbolDisplayFormat.CSharpShortErrorMessageFormat));
    }

    private static string? NamedString(AttributeData attribute, string name) =>
        attribute.NamedArguments.FirstOrDefault(a => a.Key == name).Value is { Kind: TypedConstantKind.Primitive, Value: string s } ? s : null;

    private static string[]? NamedStrings(AttributeData attribute, string name) =>
        attribute.NamedArguments.FirstOrDefault(a => a.Key == name).Value is { Kind: TypedConstantKind.Array, IsNull: false } array
            ? array.Values.Select(v => v.Value as string ?? "").ToArray()
            : null;

    private static bool IsIdentifier(string name) => SyntaxFacts.IsValidIdentifier(name) && SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None;

    // ---------- 出力の組み立て ----------

    private static string Declare(IEnumerable<Parameter> parameters) => string.Join(", ", parameters.Select(p => $"{p.Type} {p.Name}"));

    private static string Method(string doc, string access, string returnType, string nameWithTypeParameters, string parameters, string constraints, string body) =>
        $"    /// {doc}\n    {access} static {returnType} {nameWithTypeParameters}({parameters})\n{constraints}    {{\n        {body}\n    }}\n\n";

    private static string Indent(string text) =>
        string.Concat(text.Split('\n').Select((line, i) => (line.Length > 0 ? "    " + line : line) + (i < text.Split('\n').Length - 1 ? "\n" : "")));

    private static string Constraints(IEnumerable<ITypeParameterSymbol> typeParameters, Func<string, string> substitute, bool differentiate = false)
    {
        var sb = new StringBuilder();
        foreach (var t in typeParameters)
        {
            var parts = new List<string>();
            if (t.HasUnmanagedTypeConstraint || differentiate)
            {
                parts.Add("unmanaged");
            }
            else if (t.HasValueTypeConstraint)
            {
                parts.Add("struct");
            }

            if (t.HasReferenceTypeConstraint)
            {
                parts.Add("class");
            }

            if (t.HasNotNullConstraint && !differentiate)
            {
                parts.Add("notnull");
            }

            parts.AddRange(t.ConstraintTypes.Select(c => substitute(Display(c))));
            string ieee754 = $"global::System.Numerics.IFloatingPointIeee754<{t.Name}>";
            if (differentiate && !parts.Contains(ieee754))
            {
                parts.Add(ieee754);
            }

            if (t.HasConstructorConstraint && !differentiate)
            {
                parts.Add("new()");
            }

            if (parts.Count > 0)
            {
                sb.Append("        where ").Append(t.Name).Append(" : ").Append(string.Join(", ", parts)).Append('\n');
            }
        }

        return sb.ToString();
    }

    private static string Cref(IMethodSymbol method)
    {
        string typeParameters = method.TypeParameters.Length == 0 ? "" : "{" + string.Join(", ", method.TypeParameters.Select(t => t.Name)) + "}";
        string parameters = string.Join(", ", method.Parameters.Select(p => p.Type.ToDisplayString(CrefFormat)));
        return (method.Name + typeParameters + "(" + parameters + ")").Replace('<', '{').Replace('>', '}');
    }

    private static string CrefOf(Shape shape)
    {
        string typeParameters = shape.TypeParameters.Length == 0 ? "" : "{" + string.Join(", ", shape.TypeParameters) + "}";
        string parameters = string.Join(", ", shape.Parameters.Select(p => p.Type.Replace("global::", "")));
        return (shape.Name + typeParameters + "(" + parameters + ")").Replace('<', '{').Replace('>', '}');
    }

    private static string AccessibilityText(Accessibility accessibility) => accessibility switch
    {
        Accessibility.Public => "public",
        Accessibility.Private => "private",
        _ => "internal",
    };

    // C# 14 の拡張ブロック内のメソッドは、同じ受け手の拡張ブロックへ生成する。
    private static string ContainerKey(INamedTypeSymbol containing)
    {
        var types = new List<string>();
        for (var type = containing; type is not null; type = type.ContainingType)
        {
            types.Insert(0, type.IsExtension && type.ExtensionParameter is { } receiver
                ? $"extension{(type.TypeParameters.Length == 0 ? "" : $"<{string.Join(", ", type.TypeParameters.Select(t => t.Name))}>")}"
                    + $"({Display(receiver.Type)}{(receiver.Name.Length > 0 ? " " + receiver.Name : "")})"
                    + (type.TypeParameters.Length == 0 ? "" : "\n" + Constraints(type.TypeParameters, s => s).TrimEnd('\n'))
                : $"{AccessibilityText(type.DeclaredAccessibility)}{(type.IsStatic ? " static" : "")} partial class {type.Name}");
        }

        string ns = containing.ContainingNamespace.IsGlobalNamespace ? "" : containing.ContainingNamespace.ToDisplayString();
        return ns + "|" + string.Join("|", types);
    }

    private static (string Header, string Footer, string FileName) Wrap(string key)
    {
        var parts = key.Split('|');
        var header = new StringBuilder();
        var footer = new StringBuilder();
        if (parts[0].Length > 0)
        {
            header.Append("namespace ").Append(parts[0]).Append("\n{\n");
        }

        var names = new List<string> { parts[0].Length > 0 ? parts[0] : "global" };
        for (int i = 1; i < parts.Length; i++)
        {
            header.Append(parts[i]).Append("\n{\n");
            footer.Append("}\n");
            names.Add(parts[i].StartsWith("extension", StringComparison.Ordinal) ? ExtensionFileName(parts[i]) : parts[i].Substring(parts[i].LastIndexOf(' ') + 1));
        }

        if (parts[0].Length > 0)
        {
            footer.Append("}\n");
        }

        return (header.ToString(), footer.ToString(), string.Join(".", names));
    }

    // 受け手型名だけでは型引数・名前空間・制約の違いで AddSource が衝突する（CS8785）ため、宣言全体のハッシュを付与する。
    private static string ExtensionFileName(string declaration)
    {
        int open = declaration.IndexOf('(');
        string receiver = declaration.Substring(open + 1, declaration.IndexOf(')', open) - open - 1).Split(' ')[0];
        int generic = receiver.IndexOf('<');
        if (generic >= 0)
        {
            receiver = receiver.Substring(0, generic);
        }

        return $"Extension_{receiver.Substring(receiver.LastIndexOfAny(new[] { '.', ':' }) + 1)}_{StableHash(declaration):X8}";
    }

    // string.GetHashCode() はプロセスごとにランダム化されるため、決定的な FNV-1a ハッシュを使用する。
    private static uint StableHash(string text)
    {
        uint hash = 2166136261;
        foreach (char c in text)
        {
            hash = unchecked((hash ^ c) * 16777619);
        }

        return hash;
    }
